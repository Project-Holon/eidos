/*
 * engine/world/remade/rock_faces.c -- the rocks' other three faces, drawn by
 * hand (rock.c).  The map has one picture of a rock: its south face, the one
 * the field's camera sees.  A body needs an east, a north and a west face
 * too, and each is a picture of its own here: its own rim, its own peak.
 *
 * A face is rows of letters.  A row: the picture's row, the first column,
 * then a letter a pixel.  The letters are the picture's own colours from
 * dark to light (a the darkest); '.' leaves the picture's pixel.  A row must
 * cover the rock's pixels of that row exactly (rock.c checks it).  Where two
 * faces meet at the back of the body they are made to agree (rock.c).
 */

