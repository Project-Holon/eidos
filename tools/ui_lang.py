#!/usr/bin/env python3
"""tools/ui_lang.py -- engine/ui/ui_lang.tsv to engine/ui/ui_lang_table.h.

The one-screen interface draws its own labels in English; ui_tr
(engine/ui/ui_lang.c) looks each one up here and gives the game language's
words.  Rows are sorted by the FNV-1a hash of the English text, which is
what ui_tr searches by.

    python tools/ui_lang.py
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'engine', 'ui', 'ui_lang.tsv')
OUT = os.path.join(HERE, '..', 'engine', 'ui', 'ui_lang_table.h')


def fnv1a(s):
    h = 2166136261
    for b in s.encode('utf-8'):
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def c_str(s):
    out = []
    for b in s.encode('utf-8'):
        if b == 0x22 or b == 0x5C:
            out.append('\\' + chr(b))
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append('\\%03o' % b)
    return '"' + ''.join(out) + '"'


def main():
    rows = []
    seen = set()
    for n, line in enumerate(open(SRC, encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line or line.startswith('#'):
            continue
        cells = line.split('\t')
        if len(cells) != 5:
            raise SystemExit('%s:%d: %d columns, want 5' % (SRC, n, len(cells)))
        if cells[0] in seen:
            raise SystemExit('%s:%d: %r twice' % (SRC, n, cells[0]))
        seen.add(cells[0])
        rows.append((fnv1a(cells[0]), cells))
    rows.sort(key=lambda r: (r[0], r[1][0]))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* engine/ui/ui_lang_table.h -- generated by tools/ui_lang.py from\n'
                ' * engine/ui/ui_lang.tsv; sorted by the FNV-1a hash of the English. */\n\n')
        f.write('static const UiLangRow k_ui_lang[] = {\n')
        for h, c in rows:
            tr = ', '.join(c_str(x) if x else 'NULL' for x in c[1:])
            f.write('    { 0x%08Xu, %s, { %s } },\n' % (h, c_str(c[0]), tr))
        f.write('};\n')
    print('%d labels in %s' % (len(rows), os.path.relpath(OUT)))


if __name__ == '__main__':
    main()
