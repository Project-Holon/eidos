#!/usr/bin/env python3
"""The hand-made grass layers file built into the program.

    python tools/grass_inc.py

Writes engine/world/grass/tall_grass_txt.inc from engine/world/grass/tall_grass.txt: the file as C string
literals, a line each, which engine/world/bmap_grass.c includes.  Run it after every change to the layers file.
With --check it writes nothing and fails when the .inc is not what the layers file gives.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'engine', 'world', 'grass', 'tall_grass.txt')
INC = os.path.join(HERE, '..', 'engine', 'world', 'grass', 'tall_grass_txt.inc')


def build():
    out = ['/* Generated by tools/grass_inc.py from tall_grass.txt; do not edit. */\n']
    for line in open(SRC, encoding='utf-8').read().split('\n'):
        line = line.rstrip('\r')
        if line.startswith('#') or not line.strip():
            continue                    # (comments and empty lines are for the reader of the layers file)
        out.append('"%s\\n"\n' % line.replace('\\', '\\\\').replace('"', '\\"'))
    return ''.join(out)


def main():
    text = build()
    if '--check' in sys.argv[1:]:
        old = open(INC, encoding='utf-8').read() if os.path.exists(INC) else ''
        if old != text:
            sys.exit('engine/world/grass/tall_grass_txt.inc is not up to date: run tools/grass_inc.py')
        return
    with open(INC, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', os.path.normpath(INC), len(text), 'bytes')


if __name__ == '__main__':
    main()
