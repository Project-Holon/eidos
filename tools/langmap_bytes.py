#!/usr/bin/env python3
"""tools/langmap_bytes.py -- the words of English Black's data that only look
like addresses, per cartridge, for sdk/langmap_bytes.h.

sdk/langmap.c lays another cartridge's images out as English Black's and then
translates every word that looks like one of the cartridge's addresses to
English Black's.  A table of bytes can read as an address too (ov198's
window specs, 05 14 04 02), and the translation then changes data.  With
EIDOS_LANG_AUDIT pointing at English Black's extract, eidos reports each
word the translation would change although English Black holds the same
four bytes there.  This script runs that audit for each cartridge and
writes the header.

    python tools/langmap_bytes.py --eidos BUILD/eidos_boot.exe \\
        --english EXTRACT_OF_ENGLISH_BLACK \\
        --cart IRAF=PATH/extract/data --cart IRAO=PATH/extract/data ... \\
        --out sdk/langmap_bytes.h
"""

import argparse
import os
import subprocess
import sys


def audit(eidos, english, code, data_root):
    env = dict(os.environ)
    env['EIDOS_LANG_AUDIT'] = english
    env.pop('EIDOS_WINDOW_HIDDEN', None)
    p = subprocess.run([eidos, '--data-root', data_root, '--frames', '30'], env=env,
                       stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, timeout=600)
    rows = set()
    for line in p.stderr.decode('latin-1').splitlines():
        f = line.split()
        if len(f) >= 4 and f[0] == 'langaudit':
            if f[1] != code:
                sys.exit('%s: the extract is cartridge %s' % (data_root, f[1]))
            rows.add((code, int(f[2]), int(f[3], 16)))
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--eidos', required=True)
    ap.add_argument('--english', required=True, help="English Black's extract (arm9_dec.bin, overlays_dec/)")
    ap.add_argument('--cart', action='append', default=[], help='CODE=data root of that cartridge')
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    rows = set()
    for c in a.cart:
        code, root = c.split('=', 1)
        got = audit(a.eidos, a.english, code, root)
        print('%s: %d words' % (code, len(got)))
        rows |= got
    rows = sorted(rows, key=lambda r: (r[0].encode(), r[1], r[2]))
    with open(a.out, 'w', newline='\n') as f:
        f.write('/*\n'
                ' * sdk/langmap_bytes.h -- words of English Black\'s data that only look like\n'
                ' * addresses, per cartridge: sdk/langmap.c leaves them as they are.\n'
                ' * Generated by tools/langmap_bytes.py; sorted by cartridge, region (-1 the\n'
                ' * ARM9, else the overlay) and English address.\n'
                ' */\n'
                '#ifndef BW_LANGMAP_BYTES_H\n'
                '#define BW_LANGMAP_BYTES_H\n\n'
                'static const struct {\n'
                '    char code[5];\n'
                '    int region;\n'
                '    u32 addr;\n'
                '} k_byte_words[] = {\n')
        for code, region, addr in rows:
            f.write('    { "%s", %d, 0x%08Xu },\n' % (code, region, addr))
        if not rows:
            f.write('    { "", 0, 0 },\n')
        f.write('};\n\n#endif\n')
    print('%d words in %s' % (len(rows), a.out))


if __name__ == '__main__':
    main()
