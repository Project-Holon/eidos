#!/usr/bin/env python3
"""tools/ca_roots.py -- sdk/tls_mozilla_roots.c from Mozilla's root list.

The list is the one curl extracts from Mozilla's certdata.txt (the roots
Firefox trusts for servers): https://curl.se/ca/cacert.pem.  It is under the
Mozilla Public License 2.0, as certdata.txt is.  Downloads (a mod's web
request, the mods index) check a server against these roots as well as the
port's own few (sdk/tls_roots.c), so a mod can reach any site a browser
trusts; the relay keeps only its own.

  python tools/ca_roots.py CACERT.PEM      writes sdk/tls_mozilla_roots.c

Each root is a string of its own (one PEM block, under 4 KB), so no
compiler meets a limit on a string's length.  Standard library only.
"""
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    src = sys.argv[1]
    data = open(src, "rb").read()
    text = data.decode("utf-8").replace("\r\n", "\n")
    date = re.search(r"Certificate data from Mozilla as of: (.+)", text)
    # a root: its name, a line of '=', comment lines (its fingerprint), the PEM block
    blocks = re.findall(r"\n([^\n#=][^\n]*)\n=+\n(?:#[^\n]*\n)*"
                        r"(-----BEGIN CERTIFICATE-----\n.*?\n-----END CERTIFICATE-----)", text, re.S)
    if len(blocks) < 100:
        raise SystemExit("ca_roots: only %d roots found; is this curl's cacert.pem?" % len(blocks))
    out = ["/* Generated by tools/ca_roots.py; do not edit.",
           " *",
           " * Mozilla's root list as curl extracts it (https://curl.se/ca/cacert.pem),",
           " * under the Mozilla Public License 2.0 (https://mozilla.org/MPL/2.0/).",
           " * As of: %s" % (date.group(1).strip() if date else "unknown"),
           " * The file's SHA-256: %s" % hashlib.sha256(data).hexdigest(),
           " * %d roots, one PEM block a string (sdk/tls_roots.h). */" % len(blocks),
           "",
           '#include "tls_roots.h"',
           "",
           "const char *const bw_tls_mozilla_roots[] = {"]
    for name, pem in blocks:
        safe = name.strip().replace("*/", "* /").encode("ascii", "replace").decode("ascii")
        out.append("    /* %s */" % safe)
        lines = pem.split("\n")
        for i, line in enumerate(lines):
            out.append('    "%s\\n"%s' % (line, "," if i == len(lines) - 1 else ""))
    out += ["};", "",
            "const unsigned bw_tls_mozilla_root_count = %d;" % len(blocks), ""]
    dst = os.path.join(ROOT, "sdk", "tls_mozilla_roots.c")
    with open(dst, "w", newline="\n") as f:
        f.write("\n".join(out))
    print("ca_roots: %d roots -> %s" % (len(blocks), dst))


if __name__ == "__main__":
    main()
